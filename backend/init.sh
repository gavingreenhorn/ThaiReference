#!/bin/bash
set -e

# Configuration
DB_NAME="langref"
DB_USER="admin"
DB_PASS="admin"
DB_SCHEMA="thai"

echo "=== Ensuring user '$DB_USER' exists and has correct credentials ==="

sudo -iu postgres psql <<-EOF
    DO \$$ 
    BEGIN
        IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '$DB_USER') THEN
            CREATE ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASS' CREATEDB;
        ELSE
            ALTER ROLE $DB_USER WITH PASSWORD '$DB_PASS' CREATEDB;
        END IF;
    END
    \$$;
EOF

echo "=== obtaining absolute power ==="

sudo -iu postgres psql -d "$DB_NAME" <<-EOSQL
    GRANT ALL ON SCHEMA thai TO $DB_USER;
    GRANT USAGE ON SCHEMA thai TO $DB_USER;

    ALTER SCHEMA thai OWNER TO $DB_USER;

    GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA $DB_SCHEMA TO $DB_USER;
    GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA $DB_SCHEMA TO $DB_USER;
    GRANT ALL PRIVILEGES ON ALL FUNCTIONS IN SCHEMA $DB_SCHEMA TO $DB_USER;

    ALTER DEFAULT PRIVILEGES IN SCHEMA $DB_SCHEMA GRANT ALL ON TABLES TO $DB_USER;
    ALTER DEFAULT PRIVILEGES IN SCHEMA $DB_SCHEMA GRANT ALL ON SEQUENCES TO $DB_USER;
    ALTER DEFAULT PRIVILEGES IN SCHEMA $DB_SCHEMA GRANT ALL ON FUNCTIONS TO $DB_USER;
EOSQL

echo "Connection URL: postgresql+psycopg2://$DB_USER:$DB_PASS@localhost:5432/$DB_NAME"
