CREATE TABLE thai.device_group (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       character varying(255),
    max_devices integer NOT NULL DEFAULT 5,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_device_group_email UNIQUE (email)
);

CREATE TABLE thai.device (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            uuid NOT NULL,
    device_group_id bigint NOT NULL,
    platform        character varying(64),
    build           character varying(64),
    last_ip         character varying(45),
    linked_at       timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    last_seen       timestamptz,
    disabled        boolean NOT NULL DEFAULT false,
    locked          boolean NOT NULL DEFAULT false,
    CONSTRAINT uq_device_uuid UNIQUE (uuid),
    CONSTRAINT fk_device_group FOREIGN KEY (device_group_id) REFERENCES thai.device_group (id)
);

CREATE INDEX idx_device_group_id ON thai.device (device_group_id);

CREATE TABLE thai.account_token (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  character varying(64) NOT NULL,
    purpose     character varying(32) NOT NULL,
    group_id    bigint NOT NULL,
    device_uuid uuid,
    email       character varying(255),
    expires_at  bigint NOT NULL,
    used_at     timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_account_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_account_token_group FOREIGN KEY (group_id) REFERENCES thai.device_group (id)
);

CREATE INDEX idx_account_token_group ON thai.account_token (group_id);
