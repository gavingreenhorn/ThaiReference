CREATE FUNCTION thai.check_component_form() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    component_spelling text;
    component_paiboon text;
    component_ipa text;
BEGIN
    IF TG_TABLE_NAME = 'WordComponent' THEN
        SELECT s.value, t.paiboon, t."IPA"
        INTO component_spelling, component_paiboon, component_ipa
        FROM thai."SimpleWord" sw
        JOIN thai."Spelling" s ON s.id = sw.spelling_id
        JOIN thai."Transcription" t ON t.id = sw.transcription
        WHERE sw.id = NEW.word_id
        FOR SHARE OF sw, s, t;
    ELSE
        IF NOT EXISTS (SELECT 1 FROM thai."WordComponent" WHERE word_id = NEW.id) THEN
            RETURN NEW;
        END IF;
        SELECT s.value, t.paiboon, t."IPA"
        INTO component_spelling, component_paiboon, component_ipa
        FROM thai."Spelling" s CROSS JOIN thai."Transcription" t
        WHERE s.id = NEW.spelling_id AND t.id = NEW.transcription
        FOR SHARE OF s, t;
    END IF;
    IF NOT FOUND OR component_spelling IS NULL OR btrim(component_spelling) = ''
       OR component_paiboon IS NULL OR btrim(component_paiboon) = ''
       OR component_ipa IS NULL OR btrim(component_ipa) = '' THEN
        RAISE EXCEPTION 'A compound component must have spelling, Paiboon and IPA';
    END IF;
    RETURN NEW;
END
$$;

