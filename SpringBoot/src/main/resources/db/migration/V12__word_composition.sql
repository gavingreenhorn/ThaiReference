CREATE FUNCTION thai.check_compound_components(compound_word_id integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    component_count bigint;
    first_position integer;
    last_position integer;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM thai."CompoundWord" WHERE id = compound_word_id) THEN
        RETURN;
    END IF;
    SELECT count(*), min(position), max(position)
    INTO component_count, first_position, last_position
    FROM thai."WordComponent" WHERE compound_id = compound_word_id;
    IF component_count < 2 OR first_position <> 1 OR last_position <> component_count THEN
        RAISE EXCEPTION 'Compound word % must have at least two consecutively ordered components',
            compound_word_id;
    END IF;
    IF EXISTS (
        SELECT 1
        FROM thai."WordComponent" wc
        JOIN thai."SimpleWord" sw ON sw.id = wc.word_id
        JOIN thai."Spelling" s ON s.id = sw.spelling_id
        JOIN thai."Transcription" t ON t.id = sw.transcription
        WHERE wc.compound_id = compound_word_id
          AND (btrim(s.value) = '' OR t.paiboon IS NULL OR btrim(t.paiboon) = ''
               OR t."IPA" IS NULL OR btrim(t."IPA") = '')
    ) THEN
        RAISE EXCEPTION 'Compound word % has an incomplete component form', compound_word_id;
    END IF;
END
$$;

CREATE FUNCTION thai.check_compound_components_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'CompoundWord' THEN
        PERFORM thai.check_compound_components(CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END);
    ELSE
        IF TG_OP <> 'INSERT' THEN
            PERFORM thai.check_compound_components(OLD.compound_id);
        END IF;
        IF TG_OP <> 'DELETE' THEN
            PERFORM thai.check_compound_components(NEW.compound_id);
        END IF;
    END IF;
    RETURN NULL;
END
$$;

