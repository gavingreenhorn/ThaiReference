CREATE TABLE thai."SimpleWord" (
    id integer PRIMARY KEY,
    kind text GENERATED ALWAYS AS ('simple'::text) STORED,
    spelling_id integer NOT NULL REFERENCES thai."Spelling"(id),
    transcription integer NOT NULL REFERENCES thai."Transcription"(id),
    FOREIGN KEY (id, kind) REFERENCES thai."Word"(id, kind),
    UNIQUE (spelling_id, transcription)
);

CREATE TABLE thai."CompoundWord" (
    id integer PRIMARY KEY,
    kind text GENERATED ALWAYS AS ('compound'::text) STORED,
    FOREIGN KEY (id, kind) REFERENCES thai."Word"(id, kind)
);

CREATE TABLE thai."WordComponent" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compound_id integer NOT NULL REFERENCES thai."CompoundWord"(id),
    word_id integer NOT NULL REFERENCES thai."SimpleWord"(id),
    position integer NOT NULL CHECK (position > 0),
    UNIQUE (compound_id, position)
);

