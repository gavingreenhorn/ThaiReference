CREATE FUNCTION thai.check_component_form() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    component_spelling text;
    component_paiboon text;
    component_ipa text;
BEGIN
    IF TG_TABLE_NAME = 'WordComponent' THEN
        SELECT s.value, t.paiboon, t."IPA"
        INTO component_spelling, component_paiboon, component_ipa
        FROM thai."SimpleWord" sw
        JOIN thai."Spelling" s ON s.id = sw.spelling_id
        JOIN thai."Transcription" t ON t.id = sw.transcription
        WHERE sw.id = NEW.word_id
        FOR SHARE OF sw, s, t;
    ELSE
        IF NOT EXISTS (SELECT 1 FROM thai."WordComponent" WHERE word_id = NEW.id) THEN
            RETURN NEW;
        END IF;
        SELECT s.value, t.paiboon, t."IPA"
        INTO component_spelling, component_paiboon, component_ipa
        FROM thai."Spelling" s CROSS JOIN thai."Transcription" t
        WHERE s.id = NEW.spelling_id AND t.id = NEW.transcription
        FOR SHARE OF s, t;
    END IF;
    IF NOT FOUND OR component_spelling IS NULL OR btrim(component_spelling) = ''
       OR component_paiboon IS NULL OR btrim(component_paiboon) = ''
       OR component_ipa IS NULL OR btrim(component_ipa) = '' THEN
        RAISE EXCEPTION 'A compound component must have spelling, Paiboon and IPA';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER "WordComponent_form_check"
BEFORE INSERT OR UPDATE OF word_id ON thai."WordComponent"
FOR EACH ROW EXECUTE FUNCTION thai.check_component_form();

CREATE TRIGGER "SimpleWord_component_form_check"
BEFORE UPDATE OF spelling_id, transcription ON thai."SimpleWord"
FOR EACH ROW EXECUTE FUNCTION thai.check_component_form();

CREATE FUNCTION thai.check_referenced_form() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'Spelling' THEN
        IF (NEW.value IS NULL OR btrim(NEW.value) = '') AND EXISTS (
            SELECT 1 FROM thai."SimpleWord" sw
            JOIN thai."WordComponent" wc ON wc.word_id = sw.id
            WHERE sw.spelling_id = NEW.id
        ) THEN
            RAISE EXCEPTION 'A compound component spelling cannot be empty';
        END IF;
    ELSE
        IF (NEW.paiboon IS NULL OR btrim(NEW.paiboon) = ''
            OR NEW."IPA" IS NULL OR btrim(NEW."IPA") = '') AND EXISTS (
            SELECT 1 FROM thai."SimpleWord" sw
            JOIN thai."WordComponent" wc ON wc.word_id = sw.id
            WHERE sw.transcription = NEW.id
        ) THEN
            RAISE EXCEPTION 'A compound component transcription cannot be empty';
        END IF;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER "Spelling_component_form_check"
BEFORE UPDATE OF value ON thai."Spelling"
FOR EACH ROW EXECUTE FUNCTION thai.check_referenced_form();

CREATE TRIGGER "Transcription_component_form_check"
BEFORE UPDATE OF paiboon, "IPA" ON thai."Transcription"
FOR EACH ROW EXECUTE FUNCTION thai.check_referenced_form();

CREATE FUNCTION thai.check_compound_components(compound_word_id integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    component_count bigint;
    first_position integer;
    last_position integer;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM thai."CompoundWord" WHERE id = compound_word_id) THEN
        RETURN;
    END IF;
    SELECT count(*), min(position), max(position)
    INTO component_count, first_position, last_position
    FROM thai."WordComponent" WHERE compound_id = compound_word_id;
    IF component_count < 2 OR first_position <> 1 OR last_position <> component_count THEN
        RAISE EXCEPTION 'Compound word % must have at least two consecutively ordered components',
            compound_word_id;
    END IF;
    IF EXISTS (
        SELECT 1
        FROM thai."WordComponent" wc
        JOIN thai."SimpleWord" sw ON sw.id = wc.word_id
        JOIN thai."Spelling" s ON s.id = sw.spelling_id
        JOIN thai."Transcription" t ON t.id = sw.transcription
        WHERE wc.compound_id = compound_word_id
          AND (btrim(s.value) = '' OR t.paiboon IS NULL OR btrim(t.paiboon) = ''
               OR t."IPA" IS NULL OR btrim(t."IPA") = '')
    ) THEN
        RAISE EXCEPTION 'Compound word % has an incomplete component form', compound_word_id;
    END IF;
END
$$;

CREATE FUNCTION thai.check_compound_components_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'CompoundWord' THEN
        PERFORM thai.check_compound_components(CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END);
    ELSE
        IF TG_OP <> 'INSERT' THEN
            PERFORM thai.check_compound_components(OLD.compound_id);
        END IF;
        IF TG_OP <> 'DELETE' THEN
            PERFORM thai.check_compound_components(NEW.compound_id);
        END IF;
    END IF;
    RETURN NULL;
END
$$;

CREATE CONSTRAINT TRIGGER "CompoundWord_components_check"
AFTER INSERT OR UPDATE ON thai."CompoundWord"
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION thai.check_compound_components_trigger();

CREATE CONSTRAINT TRIGGER "WordComponent_components_check"
AFTER INSERT OR UPDATE OR DELETE ON thai."WordComponent"
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION thai.check_compound_components_trigger();

CREATE MATERIALIZED VIEW thai."WordView" AS
WITH simple_form AS (
    SELECT w.id, sw.spelling_id, sw.transcription AS transcription_id,
           s.value::text AS spelling, t.paiboon::text AS paiboon,
           t."IPA" AS ipa, ARRAY[]::integer[] AS component_word_ids
    FROM thai."Word" w
    JOIN thai."SimpleWord" sw ON sw.id = w.id
    JOIN thai."Spelling" s ON s.id = sw.spelling_id
    JOIN thai."Transcription" t ON t.id = sw.transcription
),
compound_form AS (
    SELECT cw.id, NULL::integer AS spelling_id, NULL::integer AS transcription_id,
           string_agg(s.value, '' ORDER BY wc.position) AS spelling,
           CASE WHEN count(t.paiboon) = count(*)
                THEN string_agg(t.paiboon, '-' ORDER BY wc.position) END AS paiboon,
           CASE WHEN count(t."IPA") = count(*)
                THEN string_agg(t."IPA", '.' ORDER BY wc.position) END AS ipa,
           array_agg(wc.word_id ORDER BY wc.position) AS component_word_ids
    FROM thai."CompoundWord" cw
    JOIN thai."WordComponent" wc ON wc.compound_id = cw.id
    JOIN thai."SimpleWord" sw ON sw.id = wc.word_id
    JOIN thai."Spelling" s ON s.id = sw.spelling_id
    JOIN thai."Transcription" t ON t.id = sw.transcription
    GROUP BY cw.id
),
forms AS (
    SELECT * FROM simple_form
    UNION ALL
    SELECT * FROM compound_form
)
SELECT f.id, f.spelling_id, f.transcription_id, f.spelling,
       f.paiboon, f.ipa,
       COALESCE(l.lexemes, ARRAY[]::text[]) AS lexemes, f.component_word_ids
FROM forms f
LEFT JOIN LATERAL (
    SELECT array_agg(l.value ORDER BY l.value)
           FILTER (WHERE l.value IS NOT NULL) AS lexemes
    FROM thai."WordLexeme" wl
    JOIN thai."Lexeme" l ON l.id = wl.lexeme
    WHERE wl.word = f.id
) l ON true
WITH NO DATA;

CREATE UNIQUE INDEX "WordView_id_idx" ON thai."WordView" (id);

CREATE INDEX "WordView_spelling_id_idx" ON thai."WordView" (spelling_id);

CREATE INDEX "WordView_transcription_id_idx" ON thai."WordView" (transcription_id);

CREATE MATERIALIZED VIEW thai."MinimalSetView" AS
WITH normalized_words AS (
    SELECT w.id AS word_id,
           regexp_replace(normalize(v.ipa, NFD), U&'[\0304\031A\032F\0361[:space:].]', '', 'g')
               AS comparison_ipa
    FROM thai."Word" w
    JOIN thai."WordView" v ON v.id = w.id
    WHERE w.is_primary = true AND v.ipa IS NOT NULL AND v.ipa <> ''
),
words AS (
    SELECT w.word_id, w.comparison_ipa,
           regexp_replace(w.comparison_ipa, U&'[\02D0\02D1\0300\0301\0302\030C\1DC4\1DC5\1DC6\1DC7]',
                          '', 'g') AS comparison_key,
           init.label
    FROM normalized_words w
    JOIN LATERAL (
        SELECT snd.value AS label
        FROM thai."Sound" snd
        WHERE snd.consonant_sound = 1 AND snd.value IS NOT NULL AND snd.value <> ''
          AND (starts_with(w.comparison_ipa,
                           regexp_replace(normalize(snd.value, NFD), U&'[\0361]', '', 'g'))
               OR (snd.value = U&'\0294' AND w.comparison_ipa ~ U&'^[aeiou\025B\0264\0254\026F]'))
        ORDER BY length(snd.value) DESC, snd.initial_only DESC, snd.id
        LIMIT 1
    ) init ON true
    WHERE w.comparison_ipa <> ''
),
sets AS (
    SELECT label, comparison_key, row_number() OVER (ORDER BY label, comparison_key) AS set_id
    FROM words
    GROUP BY label, comparison_key
    HAVING count(DISTINCT comparison_ipa) > 1
)
SELECT st.set_id, st.label, w.word_id
FROM sets st
JOIN words w ON w.label = st.label AND w.comparison_key = st.comparison_key
ORDER BY st.set_id, w.word_id
WITH NO DATA;

CREATE UNIQUE INDEX "MinimalSetView_set_word_uq" ON thai."MinimalSetView" (set_id, word_id);

CREATE INDEX "MinimalSetView_label_set_idx" ON thai."MinimalSetView" (label, set_id);
