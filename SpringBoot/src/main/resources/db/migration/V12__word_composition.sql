CREATE FUNCTION thai.lock_compound_components() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.compound_id <> NEW.compound_id THEN
        PERFORM id FROM thai."Word"
        WHERE id IN (OLD.compound_id, NEW.compound_id)
        ORDER BY id FOR UPDATE;
    ELSE
        PERFORM id FROM thai."Word"
        WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.compound_id ELSE NEW.compound_id END
        FOR UPDATE;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END
$$;

