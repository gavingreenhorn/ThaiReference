                     additional_gloss, share_second_lexeme, color_labels)
    LOOP
    SELECT count(*) INTO expected_names FROM thai."Color"
    WHERE english_label = ANY(entry.color_labels);
    IF EXISTS (
        SELECT 1 FROM unnest(entry.color_labels) AS expected(label)
        WHERE (SELECT count(*) FROM thai."Color" WHERE english_label = expected.label) <> 1
    ) THEN
        RAISE EXCEPTION 'Expected exactly one of each audited color name for %', entry.whole;
    END IF;
    SELECT count(*), min(sw.id) INTO candidate_count, first_id
    FROM thai."SimpleWord" sw JOIN thai."Spelling" s ON s.id = sw.spelling_id
    WHERE s.value = entry.first_component;
    IF candidate_count <> 1 THEN
        RAISE EXCEPTION 'Expected one component % for %, found %',
            entry.first_component, entry.whole, candidate_count;
    END IF;
    SELECT count(*), min(sw.id) INTO candidate_count, second_id
    FROM thai."SimpleWord" sw JOIN thai."Spelling" s ON s.id = sw.spelling_id
    WHERE s.value = entry.second_component;
    IF candidate_count <> 1 THEN
        RAISE EXCEPTION 'Expected one component % for %, found %',
            entry.second_component, entry.whole, candidate_count;
    END IF;
    SELECT count(*) INTO matched_names
    FROM thai."Color" c JOIN thai."CompositeName" cn ON cn.id = c.composite_name_id
    WHERE c.english_label = ANY(entry.color_labels)
      AND ((cn.word1 = first_id AND cn.word2 = second_id)
        OR (cn.word2 = first_id AND cn.word3 = second_id)
        OR (cn.word3 = first_id AND cn.word4 = second_id)
        OR (cn.word4 = first_id AND cn.word5 = second_id));
    IF matched_names <> expected_names THEN
        RAISE EXCEPTION 'Audited color names for % have changed', entry.whole;
    END IF;
    IF EXISTS (
        SELECT 1 FROM thai."SimpleWord" sw
        JOIN thai."Spelling" s ON s.id = sw.spelling_id
        WHERE s.value = entry.whole
    ) THEN
        RAISE EXCEPTION 'Existing word % requires identity review before name conversion', entry.whole;
    END IF;

    INSERT INTO thai."Word"(kind, is_primary) VALUES ('compound', true) RETURNING id INTO word_id;
    INSERT INTO thai."CompoundWord"(id) VALUES (word_id);
    INSERT INTO thai."WordComponent"(compound_id, word_id, position)
    VALUES (word_id, first_id, 1), (word_id, second_id, 2);
    INSERT INTO thai."Lexeme"(value, part_of_speech) VALUES (entry.gloss, entry.part_of_speech)
    ON CONFLICT (value, part_of_speech) DO NOTHING;
    SELECT id INTO STRICT lexeme_id FROM thai."Lexeme"
    WHERE value = entry.gloss AND part_of_speech = entry.part_of_speech;
    INSERT INTO thai."WordLexeme"(word, lexeme) VALUES (word_id, lexeme_id);
    IF entry.share_second_lexeme AND NOT EXISTS (
        SELECT 1 FROM thai."WordLexeme" WHERE word = second_id AND lexeme = lexeme_id
    ) THEN
        INSERT INTO thai."WordLexeme"(word, lexeme) VALUES (second_id, lexeme_id);
    END IF;
    IF entry.additional_gloss IS NOT NULL THEN
        INSERT INTO thai."Lexeme"(value, part_of_speech) VALUES (entry.additional_gloss, 'noun')
        ON CONFLICT (value, part_of_speech) DO NOTHING;
        SELECT id INTO STRICT lexeme_id FROM thai."Lexeme"
        WHERE value = entry.additional_gloss AND part_of_speech = 'noun';
        INSERT INTO thai."WordLexeme"(word, lexeme) VALUES (word_id, lexeme_id);
    END IF;

    FOR name_row IN
        SELECT DISTINCT cn.id, cn.word1, cn.word2, cn.word3, cn.word4, cn.word5
        FROM thai."CompositeName" cn
        JOIN thai."Color" c ON c.composite_name_id = cn.id
        WHERE c.english_label = ANY(entry.color_labels)
    LOOP
        IF EXISTS (SELECT 1 FROM thai."Color" c
                   WHERE c.composite_name_id = name_row.id
                     AND (c.english_label IS NULL
                          OR NOT (c.english_label = ANY(entry.color_labels))))
           OR EXISTS (SELECT 1 FROM thai."Season" WHERE name = name_row.id)
           OR EXISTS (SELECT 1 FROM thai."Direction" WHERE composite_name_id = name_row.id)
           OR EXISTS (SELECT 1 FROM thai."Position" WHERE composite_name_id = name_row.id)
           OR EXISTS (SELECT 1 FROM thai."Class" WHERE name = name_row.id)
           OR EXISTS (SELECT 1 FROM thai."ToneMark" WHERE name = name_row.id) THEN
            RAISE EXCEPTION 'Shared name % for % needs separate review', name_row.id, entry.whole;
        END IF;
        IF (name_row.word1 IS NULL AND (name_row.word2 IS NOT NULL OR name_row.word3 IS NOT NULL
                                       OR name_row.word4 IS NOT NULL OR name_row.word5 IS NOT NULL))
           OR (name_row.word2 IS NULL AND (name_row.word3 IS NOT NULL OR name_row.word4 IS NOT NULL
                                          OR name_row.word5 IS NOT NULL))
           OR (name_row.word3 IS NULL AND (name_row.word4 IS NOT NULL OR name_row.word5 IS NOT NULL))
           OR (name_row.word4 IS NULL AND name_row.word5 IS NOT NULL) THEN
            RAISE EXCEPTION 'Name % has gaps in its word slots', name_row.id;
        END IF;
        original_parts := array_remove(
            ARRAY[name_row.word1, name_row.word2, name_row.word3, name_row.word4, name_row.word5], NULL);
        updated_parts := ARRAY[]::integer[];
        part_index := 1;
        replacements := 0;
        WHILE part_index <= cardinality(original_parts) LOOP
            IF part_index < cardinality(original_parts)
               AND original_parts[part_index] = first_id
               AND original_parts[part_index + 1] = second_id THEN
                updated_parts := array_append(updated_parts, word_id);
                replacements := replacements + 1;
                part_index := part_index + 2;
            ELSE
                updated_parts := array_append(updated_parts, original_parts[part_index]);
                part_index := part_index + 1;
            END IF;
        END LOOP;
        IF replacements <> 1 THEN
            RAISE EXCEPTION 'Name % has ambiguous compound references', name_row.id;
        END IF;
        UPDATE thai."CompositeName"
        SET word1 = updated_parts[1], word2 = updated_parts[2], word3 = updated_parts[3],
            word4 = updated_parts[4], word5 = updated_parts[5]
        WHERE id = name_row.id;
    END LOOP;
    END LOOP;
END
$$;

CREATE MATERIALIZED VIEW thai."WordView" AS
WITH simple_form AS (
    SELECT w.id, sw.spelling_id, sw.transcription AS transcription_id,
           s.value::text AS spelling, t.paiboon::text AS paiboon,
           t."IPA" AS ipa, ARRAY[]::integer[] AS component_word_ids
    FROM thai."Word" w
    JOIN thai."SimpleWord" sw ON sw.id = w.id
    JOIN thai."Spelling" s ON s.id = sw.spelling_id
    JOIN thai."Transcription" t ON t.id = sw.transcription
),
compound_form AS (
    SELECT cw.id, NULL::integer AS spelling_id, NULL::integer AS transcription_id,
           string_agg(s.value, '' ORDER BY wc.position) AS spelling,
           CASE WHEN count(t.paiboon) = count(*)
                THEN string_agg(t.paiboon, '-' ORDER BY wc.position) END AS paiboon,
           CASE WHEN count(t."IPA") = count(*)
                THEN string_agg(t."IPA", '.' ORDER BY wc.position) END AS ipa,
           array_agg(wc.word_id ORDER BY wc.position) AS component_word_ids
    FROM thai."CompoundWord" cw
    JOIN thai."WordComponent" wc ON wc.compound_id = cw.id
    JOIN thai."SimpleWord" sw ON sw.id = wc.word_id
    JOIN thai."Spelling" s ON s.id = sw.spelling_id
    JOIN thai."Transcription" t ON t.id = sw.transcription
    GROUP BY cw.id
),
forms AS (
    SELECT * FROM simple_form
    UNION ALL
    SELECT * FROM compound_form
)
SELECT f.id, f.spelling_id, f.transcription_id, f.spelling,
       f.paiboon, f.ipa,
       COALESCE(l.lexemes, ARRAY[]::text[]) AS lexemes, f.component_word_ids
FROM forms f
LEFT JOIN LATERAL (
    SELECT array_agg(l.value ORDER BY l.value)
           FILTER (WHERE l.value IS NOT NULL) AS lexemes
    FROM thai."WordLexeme" wl
    JOIN thai."Lexeme" l ON l.id = wl.lexeme
    WHERE wl.word = f.id
) l ON true
WITH NO DATA;

CREATE UNIQUE INDEX "WordView_id_idx" ON thai."WordView" (id);
CREATE INDEX "WordView_spelling_id_idx" ON thai."WordView" (spelling_id);
CREATE INDEX "WordView_transcription_id_idx" ON thai."WordView" (transcription_id);
REFRESH MATERIALIZED VIEW thai."WordView";

DO $$
BEGIN
    IF EXISTS (
        SELECT v.spelling, normalize(v.paiboon, NFC), normalize(v.ipa, NFC)
        FROM thai."WordView" v
        JOIN thai."Word" w ON w.id = v.id
        GROUP BY v.spelling, normalize(v.paiboon, NFC), normalize(v.ipa, NFC)
        HAVING count(*) > 1 AND bool_or(w.kind = 'compound')
    ) THEN
        RAISE EXCEPTION 'Derived compound form collides with another word';
    END IF;
END
$$;

CREATE MATERIALIZED VIEW thai."MinimalSetView" AS
WITH normalized_words AS (
    SELECT w.id AS word_id,
           regexp_replace(normalize(v.ipa, NFD), U&'[\0304\031A\032F\0361[:space:].]', '', 'g')
               AS comparison_ipa
    FROM thai."Word" w
    JOIN thai."WordView" v ON v.id = w.id
    WHERE w.is_primary = true AND v.ipa IS NOT NULL AND v.ipa <> ''
),
words AS (
    SELECT w.word_id, w.comparison_ipa,
           regexp_replace(w.comparison_ipa, U&'[\02D0\02D1\0300\0301\0302\030C\1DC4\1DC5\1DC6\1DC7]',
                          '', 'g') AS comparison_key,
           init.label
    FROM normalized_words w
    JOIN LATERAL (
        SELECT snd.value AS label
        FROM thai."Sound" snd
        WHERE snd.consonant_sound = 1 AND snd.value IS NOT NULL AND snd.value <> ''
          AND (starts_with(w.comparison_ipa,
                           regexp_replace(normalize(snd.value, NFD), U&'[\0361]', '', 'g'))
               OR (snd.value = U&'\0294' AND w.comparison_ipa ~ U&'^[aeiou\025B\0264\0254\026F]'))
        ORDER BY length(snd.value) DESC, snd.initial_only DESC, snd.id
        LIMIT 1
    ) init ON true
    WHERE w.comparison_ipa <> ''
),
sets AS (
    SELECT label, comparison_key, row_number() OVER (ORDER BY label, comparison_key) AS set_id
    FROM words
    GROUP BY label, comparison_key
    HAVING count(DISTINCT comparison_ipa) > 1
)
SELECT st.set_id, st.label, w.word_id
FROM sets st
JOIN words w ON w.label = st.label AND w.comparison_key = st.comparison_key
ORDER BY st.set_id, w.word_id
WITH NO DATA;

CREATE UNIQUE INDEX "MinimalSetView_set_word_uq" ON thai."MinimalSetView" (set_id, word_id);
CREATE INDEX "MinimalSetView_label_set_idx" ON thai."MinimalSetView" (label, set_id);
REFRESH MATERIALIZED VIEW thai."MinimalSetView";
