CREATE SCHEMA thai;
CREATE TABLE thai."Spelling"(id integer PRIMARY KEY, value text NOT NULL);
CREATE TABLE thai."Transcription"(id integer PRIMARY KEY, "IPA" text, paiboon text);
CREATE TABLE thai."Word"(
	id integer PRIMARY KEY, spelling_id integer REFERENCES thai."Spelling",
	transcription integer REFERENCES thai."Transcription", is_primary boolean DEFAULT true
);
CREATE TABLE thai."Lexeme"(
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	value text, part_of_speech text
);
CREATE TABLE thai."WordLexeme"(
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	word integer REFERENCES thai."Word", lexeme integer REFERENCES thai."Lexeme"
);
CREATE TABLE thai."MinimalSetWord"(
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	set_id integer, word_id integer REFERENCES thai."Word"
);
CREATE TABLE thai."Consonant"(id integer PRIMARY KEY, transcription integer REFERENCES thai."Transcription");
CREATE TABLE thai."SentenceWord"(
	id integer PRIMARY KEY, sentence_id integer, word_id integer REFERENCES thai."Word",
	word_order integer, UNIQUE(sentence_id,word_order)
);

